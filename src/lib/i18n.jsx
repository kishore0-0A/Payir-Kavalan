const LanguageContext = createContext({
  lang: 'en',
  /** @param {string} code */
  setLang: (code) => {},
  /** @param {string} key */
  t: (key) => key,
  languages: LANGUAGES
});

/** @param {{ children?: React.ReactNode }} props */
export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    try {
      const saved = localStorage.getItem('cc_lang');
      return LANGUAGES.find((item) => item.code === saved)?.code || 'en';
    } catch {
      return 'en';
    }
  });

  /** @param {string} code */
  const setLang = (code) => {
    const valid = LANGUAGES.find((item) => item.code === code)?.code || 'en';

    try {
      localStorage.setItem('cc_lang', valid);
    } catch {}

    // Clear legacy googtrans cookies that may have caused DOM reconciliation crashes
    try {
      document.cookie = "googtrans=; expires=Thu, 01 Jan 1970 00:00:00 UTC; path=/;";
      document.cookie = "googtrans=; expires=Thu, 01 Jan 1970 00:00:00 UTC; domain=" + window.location.hostname + "; path=/;";
    } catch {}

    setLangState(valid);

    // Sync preference to backend if logged in
    try {
      const token = localStorage.getItem('token');
      if (token) {
        fetch('http://localhost:8000/api/auth/me', {
          method: 'PUT',
          headers: {
            'Content-Type': 'application/json',
            'Authorization': `Bearer ${token}`
          },
          body: JSON.stringify({ preferred_language: valid })
        }).catch(() => {});
      }
    } catch {}
  };

  useEffect(() => {
    try {
      document.documentElement.lang = lang || 'en';
      document.documentElement.dir = 'ltr';
    } catch {}
  }, [lang]);

  // Initial backend sync if user has saved language preference
  useEffect(() => {
    try {
      const token = localStorage.getItem('token');
      if (token) {
        fetch('http://localhost:8000/api/auth/me', {
          headers: { 'Authorization': `Bearer ${token}` }
        })
          .then((r) => r.ok ? r.json() : null)
          .then((user) => {
            if (user?.preferred_language && LANGUAGES.some(l => l.code === user.preferred_language)) {
              if (user.preferred_language !== lang) {
                setLangState(user.preferred_language);
                try { localStorage.setItem('cc_lang', user.preferred_language); } catch {}
              }
            }
          })
          .catch(() => {});
      }
    } catch {}
  }, []);

  /**
   * Safe translation lookup with guaranteed string fallback
   * @param {string} key
   * @param {string} [fallback]
   */
  const t = (key, fallback = '') => {
    if (!key || typeof key !== 'string') return fallback || '';
    const entry = T[key];

    if (!entry) {
      return fallback || key;
    }

    const val = entry[lang] ?? entry.en ?? fallback ?? key;
    return typeof val === 'string' ? val : String(val);
  };

  return (
    <LanguageContext.Provider
      value={{
        lang: lang || 'en',
        setLang,
        t,
        languages: LANGUAGES
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  return useContext(LanguageContext);
}