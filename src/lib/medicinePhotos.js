/**
 * Returns the transparent PNG product image path for any given medicine or active ingredient.
 */
export function getMedicinePhoto(medName = '') {
  if (!medName) return MEDICINE_PHOTOS.default;
  const lower = medName.toLowerCase();
  
  for (const [key, path] of Object.entries(MEDICINE_PHOTOS)) {
    if (key !== 'default' && lower.includes(key)) {
      return path;
    }
  }
  
  return MEDICINE_PHOTOS.default;
}
