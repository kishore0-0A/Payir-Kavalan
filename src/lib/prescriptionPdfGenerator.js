/**
 * Generates an ultra-clean, high-resolution printable PDF using html2canvas and jsPDF.
 * Renders Unicode Tamil & Hindi cleanly via the browser engine canvas.
 */
export async function generatePrescriptionPDF({ diagnosis, prescription, lang = 'en', tankSize = 15 }) {
  const t = PRESCRIPTION_I18N[lang] || PRESCRIPTION_I18N.en;
  const confidencePercent = Math.round((diagnosis.confidence || 0) * 100);

  // Hidden off-screen render container
  const container = document.createElement('div');
  container.style.position = 'fixed';
  container.style.top = '-9999px';
  container.style.left = '-9999px';
  container.style.width = '794px'; // Standard A4 width at 96 DPI
  container.style.backgroundColor = '#ffffff';
  container.style.color = '#1e293b';
  container.style.fontFamily = "'Inter', 'Noto Sans Tamil', 'Noto Sans Devanagari', -apple-system, sans-serif";
  container.style.padding = '36px 40px';
  container.style.boxSizing = 'border-box';
  container.style.lineHeight = '1.45';

  const dateStr = new Date(diagnosis.created_date || Date.now()).toLocaleDateString(
    lang === 'ta' ? 'ta-IN' : (lang === 'hi' ? 'hi-IN' : 'en-IN'),
    { year: 'numeric', month: 'long', day: 'numeric', hour: '2-digit', minute: '2-digit' }
  );

  const localizedCrop = getLocalizedText(diagnosis.crop_name || 'Tomato', lang);
  const localizedCondition = getLocalizedText(diagnosis.predicted_disease || 'Healthy Plant', lang);
  const localizedSeverity = getLocalizedText(diagnosis.severity || 'Moderate', lang);

  const medicinesList = prescription.medicines || [];
  const immediateActions = prescription.immediateActions || [];
  const preventionStrategy = prescription.preventionStrategy || [];
  const future = prescription.futurePossibilities || {};

  const tankMixLabel = lang === 'ta'
    ? `${tankSize} லிட்டர் தெளிப்பானுக்கு சுமார் ${(tankSize * 2.5).toFixed(0)} கிராம் / ${(tankSize * 1.5).toFixed(0)} மி.லி கலக்கவும்`
    : (lang === 'hi'
      ? `${tankSize}L टंकी में लगभग ${(tankSize * 2.5).toFixed(0)} ग्राम / ${(tankSize * 1.5).toFixed(0)} ml मिलाएं`
      : `Mix approx. ${(tankSize * 2.5).toFixed(0)}g / ${(tankSize * 1.5).toFixed(0)}ml per ${tankSize}L pump`);

  container.innerHTML = `
    <!-- Top Header Brand Banner -->
    <div style="border-bottom: 2.5px solid #059669; padding-bottom: 14px; margin-bottom: 18px; display: flex; justify-content: space-between; align-items: flex-end;">
      <div>
        <div style="font-size: 20px; font-weight: 800; color: #047857; letter-spacing: 0.5px; text-transform: uppercase;">
          ${t.title}
        </div>
        <div style="font-size: 11px; color: #64748b; font-weight: 500; margin-top: 3px;">
          ${t.subtitle}
        </div>
      </div>
      <div style="text-align: right; font-size: 11px; color: #475569;">
        <div><strong>${t.date}:</strong></div>
        <div style="color: #0f172a; font-weight: 600;">${dateStr}</div>
      </div>
    </div>

    <!-- Key Metadata Cards Grid -->
    <div style="display: grid; grid-template-columns: 1fr 1.6fr 1fr 1fr; gap: 10px; margin-bottom: 18px;">
      <div style="background: #f8fafc; border: 1px solid #e2e8f0; border-radius: 10px; padding: 10px 12px;">
        <div style="font-size: 10px; font-weight: 700; color: #64748b; text-transform: uppercase;">${t.crop}</div>
        <div style="font-size: 14px; font-weight: 700; color: #0f172a; margin-top: 2px;">${localizedCrop}</div>
      </div>
      <div style="background: #ecfdf5; border: 1px solid #a7f3d0; border-radius: 10px; padding: 10px 12px;">
        <div style="font-size: 10px; font-weight: 700; color: #065f46; text-transform: uppercase;">${t.condition}</div>
        <div style="font-size: 13px; font-weight: 800; color: #047857; margin-top: 2px; line-height: 1.3;">${localizedCondition}</div>
      </div>
      <div style="background: #f8fafc; border: 1px solid #e2e8f0; border-radius: 10px; padding: 10px 12px;">
        <div style="font-size: 10px; font-weight: 700; color: #64748b; text-transform: uppercase;">${t.confidence}</div>
        <div style="font-size: 14px; font-weight: 800; color: #0284c7; margin-top: 2px;">${confidencePercent}%</div>
      </div>
      <div style="background: #f8fafc; border: 1px solid #e2e8f0; border-radius: 10px; padding: 10px 12px;">
        <div style="font-size: 10px; font-weight: 700; color: #64748b; text-transform: uppercase;">${t.severity}</div>
        <div style="font-size: 13px; font-weight: 700; color: ${diagnosis.severity === 'severe' ? '#b91c1c' : '#d97706'}; text-transform: capitalize; margin-top: 2px;">
          ${localizedSeverity}
        </div>
      </div>
    </div>

    <!-- Section 1: Prescribed Medicines & Dosages -->
    <div style="margin-bottom: 16px;">
      <div style="font-size: 12px; font-weight: 800; color: #065f46; background: #d1fae5; border-left: 4px solid #059669; padding: 5px 10px; border-radius: 4px; text-transform: uppercase; margin-bottom: 8px;">
        ${t.sprayerHeading} (${tankSize}L)
      </div>
      <div style="display: flex; flex-direction: column; gap: 8px;">
        ${medicinesList.map((m, idx) => {
          const photoUrl = getMedicinePhoto(m.name);
          return `
          <div style="background: #ffffff; border: 1px solid #cbd5e1; border-radius: 8px; padding: 8px 10px; font-size: 11px; display: flex; gap: 10px; align-items: center;">
            <div style="width: 54px; height: 54px; flex-shrink: 0; background: #f8fafc; border: 1px solid #e2e8f0; border-radius: 6px; padding: 3px; display: flex; align-items: center; justify-content: center;">
              <img src="${photoUrl}" alt="${m.name}" style="max-width: 100%; max-height: 100%; object-fit: contain;" crossorigin="anonymous" />
            </div>
            <div style="flex: 1; min-width: 0;">
              <div style="display: flex; justify-content: space-between; align-items: baseline; margin-bottom: 3px;">
                <span style="font-weight: 800; font-size: 11.5px; color: #0f172a;">#${idx + 1}. ${m.name}</span>
                <span style="font-size: 9.5px; font-weight: 600; color: #059669; background: #ecfdf5; border: 1px solid #a7f3d0; padding: 1px 5px; border-radius: 4px;">${getLocalizedText(m.type, lang)}</span>
              </div>
              <div style="display: grid; grid-template-columns: 1.3fr 1.2fr 0.9fr; gap: 6px; color: #334155; font-size: 10.5px;">
                <div><strong>${t.dosage}:</strong> ${getLocalizedText(m.dosage, lang)} (${tankMixLabel})</div>
                <div><strong>${t.timing}:</strong> ${getLocalizedText(m.timing, lang)}</div>
                <div><strong>${t.preHarvest}:</strong> ${getLocalizedText(m.preHarvestInterval || '0 days', lang)}</div>
              </div>
              ${m.instructions ? `<div style="font-size: 9.5px; color: #64748b; font-style: italic; margin-top: 3px; border-top: 1px dashed #e2e8f0; padding-top: 2px;">💡 ${t.tip}: ${getLocalizedText(m.instructions, lang)}</div>` : ''}
            </div>
          </div>
        `;}).join('')}
      </div>
    </div>

    <!-- Section 2: Immediate Actions & Long Term Prevention -->
    <div style="display: grid; grid-template-columns: 1fr 1fr; gap: 12px; margin-bottom: 16px;">
      <!-- Immediate Actions -->
      <div style="background: #fffbeb; border: 1px solid #fde68a; border-radius: 8px; padding: 10px 12px;">
        <div style="font-size: 11px; font-weight: 800; color: #b45309; text-transform: uppercase; margin-bottom: 6px; border-bottom: 1px solid #fef3c7; padding-bottom: 3px;">
          ${t.actionHeading}
        </div>
        <ol style="margin: 0; padding-left: 16px; font-size: 11px; color: #78350f; display: flex; flex-direction: column; gap: 4px;">
          ${immediateActions.map(act => `<li style="line-height: 1.35;">${getLocalizedText(act, lang)}</li>`).join('')}
        </ol>
      </div>

      <!-- Prevention Protocol -->
      <div style="background: #f0fdf4; border: 1px solid #bbf7d0; border-radius: 8px; padding: 10px 12px;">
        <div style="font-size: 11px; font-weight: 800; color: #15803d; text-transform: uppercase; margin-bottom: 6px; border-bottom: 1px solid #dcfce7; padding-bottom: 3px;">
          ${t.preventionHeading}
        </div>
        <ul style="margin: 0; padding-left: 16px; font-size: 11px; color: #14532d; display: flex; flex-direction: column; gap: 4px;">
          ${preventionStrategy.map(prev => `<li style="line-height: 1.35;">${getLocalizedText(prev, lang)}</li>`).join('')}
        </ul>
      </div>
    </div>

    <!-- Section 3: Future Prognosis & Timeline -->
    <div style="background: #f0f9ff; border: 1px solid #bae6fd; border-radius: 8px; padding: 10px 12px; margin-bottom: 14px; font-size: 11px;">
      <div style="font-size: 11px; font-weight: 800; color: #0369a1; text-transform: uppercase; margin-bottom: 6px;">
        ${t.prognosisHeading}
      </div>
      <div style="margin-bottom: 4px;"><strong>${t.outlook}:</strong> ${getLocalizedText(future.prognosis || 'Follow prescribed spray regimen for optimal recovery.', lang)}</div>
      <div style="display: grid; grid-template-columns: 1fr 1fr; gap: 10px; margin-top: 5px;">
        <div style="background: #ffffff; padding: 6px 8px; border-radius: 6px; border: 1px solid #e0f2fe;">
          <strong style="color: #0284c7;">${t.day3to5}:</strong> ${getLocalizedText(future.day3to5 || 'Lesions stop multiplying.', lang)}
        </div>
        <div style="background: #ffffff; padding: 6px 8px; border-radius: 6px; border: 1px solid #e0f2fe;">
          <strong style="color: #059669;">${t.day7to14}:</strong> ${getLocalizedText(future.day7to14 || 'Clean green shoots emerge.', lang)}
        </div>
      </div>
      ${future.warningSign ? `<div style="margin-top: 6px; color: #b91c1c; font-weight: 600;">⚠️ ${t.warning}: ${getLocalizedText(future.warningSign, lang)}</div>` : ''}
    </div>

    <!-- Safety & PPE Guidelines -->
    <div style="background: #f8fafc; border-left: 3px solid #64748b; padding: 7px 10px; font-size: 10px; color: #475569; margin-bottom: 14px;">
      <strong>${t.safetyHeading}:</strong> ${t.safetyText}
    </div>

    <!-- Footer Signoff -->
    <div style="border-top: 1px solid #e2e8f0; padding-top: 10px; display: flex; justify-content: space-between; align-items: center; font-size: 9px; color: #94a3b8;">
      <div>${t.verifiedBy}</div>
      <div style="max-width: 480px; text-align: right; line-height: 1.2;">${t.disclaimer}</div>
    </div>
  `;

  document.body.appendChild(container);

  try {
    const canvas = await html2canvas(container, {
      scale: 2, // High resolution rendering for sharp print text
      useCORS: true,
      logging: false,
      backgroundColor: '#ffffff'
    });

    const imgData = canvas.toDataURL('image/jpeg', 0.95);
    const pdf = new jsPDF('p', 'mm', 'a4');
    const pdfWidth = pdf.internal.pageSize.getWidth();
    const pdfHeight = (canvas.height * pdfWidth) / canvas.width;

    pdf.addImage(imgData, 'JPEG', 0, 0, pdfWidth, pdfHeight);
    pdf.save(`Payir-Kaavalan-Prescription-${diagnosis.crop_name || 'crop'}-${lang}.pdf`);
  } finally {
    document.body.removeChild(container);
  }
}
